@pytest.mark.requires_desktop_package
def test_frozen_latex2mathml_output_matches_source_tree(packaged, tmp_path):
    """AC2: the bundled probe converts the SAME fixtures the source tree
    converts in this very process; outputs must be byte-identical, and the
    bundled symbol table must hash-match the source venv's copy."""

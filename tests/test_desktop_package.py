def test_freeze_support_is_first_statement_of_main_guard():
    """AC3 static half: the guard's FIRST statement is freeze_support(), so a
    frozen spawn child is intercepted before main() touches the control stream."""
    tree = ast.parse(DESKTOP_CHILD.read_text(encoding="utf-8"))
    guards = [
        node
        for node in tree.body
        if isinstance(node, ast.If)
        and isinstance(node.test, ast.Compare)
        and isinstance(node.test.left, ast.Name)
        and node.test.left.id == "__name__"
    ]
    assert len(guards) == 1, "expected exactly one __main__ guard"
    first = guards[0].body[0]
    assert isinstance(first, ast.Expr) and isinstance(first.value, ast.Call)
    call = first.value.func
    assert isinstance(call, ast.Attribute) and call.attr == "freeze_support"
    assert isinstance(call.value, ast.Name) and call.value.id == "multiprocessing"


def test_exception_set_is_closed_and_size_pinned():
    """AC1's tripwire: the nondeterminism exception set is a frozenset whose
    exact size AND membership are pinned in two files; silent growth fails."""
    dp = _driver()
    assert isinstance(dp.NONDETERMINISTIC_EXCEPTIONS, frozenset)
    assert dp.EXPECTED_EXCEPTION_COUNT == PINNED_EXCEPTION_COUNT
    assert len(dp.NONDETERMINISTIC_EXCEPTIONS) == PINNED_EXCEPTION_COUNT
    assert dp.NONDETERMINISTIC_EXCEPTIONS == PINNED_EXCEPTIONS


def test_scanner_finds_needle_in_binary_and_extensionless_files(tmp_path):
    dp = _driver()
    needles = {"home": b"/Users/buildbot-home"}
    (tmp_path / "clean.dylib").write_bytes(os.urandom(64) + b"\x00clean\x00")
    (tmp_path / "leaky.pyc").write_bytes(b"\x00" * 32 + b"/Users/buildbot-home/x.py\x00")
    (tmp_path / "no-extension").write_bytes(b"prefix /Users/buildbot-home tail")
    report = dp.scan_tree(tmp_path, needles)
    assert set(report["hits"]) == {"leaky.pyc", "no-extension"}
    assert report["files_scanned"] == 3
    assert report["bytes_scanned"] == report["lstat_bytes"]


def test_scanner_reads_nested_zip_members(tmp_path):
    """A raw byte grep cannot see inside deflated members; the scanner must."""
    import zipfile

    dp = _driver()
    archive = tmp_path / "base_library.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("mod.pyc", b"A" * 512 + b"/Users/buildbot-home/mod.py" + b"B" * 512)
    report = dp.scan_tree(tmp_path, {"home": b"/Users/buildbot-home"})
    hits = report["hits"]["base_library.zip"]
    assert any(entry.startswith("zip:mod.pyc") for entry in hits)
    assert report["zip_pyc_members"] == 1



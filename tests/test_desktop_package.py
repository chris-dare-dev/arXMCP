@pytest.mark.requires_desktop_package
def test_bundle_executables_exist_and_are_signed(packaged):
    """The artifact later signing work consumes: both executables present and
    carrying a valid (ad-hoc at this stage) macOS signature."""
    dp, report = packaged
    bundle = Path(report["bundle"])
    for name in (dp.CHILD_EXE, dp.PROBE_EXE):
        exe = bundle / name
        assert exe.is_file() and os.access(exe, os.X_OK)
    if sys.platform == "darwin":
        proc = subprocess.run(
            ["/usr/bin/codesign", "--verify", "--strict", str(bundle / dp.CHILD_EXE)],
            capture_output=True,
            text=True,
            timeout=120,
        )
        assert proc.returncode == 0, f"codesign verify failed: {proc.stderr}"

"""desktop-distribution-m7 packaging gate: PyInstaller bundle hygiene.

Fast tests run in every ``make test``. The ``requires_desktop_package``-marked
tests are the authoritative AC1-AC5 evidence: they provision the hash-pinned
build venv, run TWO independent ~74 s PyInstaller builds, and assert against
the real frozen artifact — never a mock (the hollow-mock precedent this file
must not repeat is ``test_desktop_sidecar_spike.py::test_probe_calls_freeze_support``,
which proves a monkeypatched ``freeze_support`` was called, not that the
frozen re-exec guard works). Run them via ``make desktop-package-check``,
whose ``DESKTOP_PACKAGE_GATE=1`` makes any skip fail the session.
"""

from __future__ import annotations

import ast
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess

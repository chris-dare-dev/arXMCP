from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
DRIVER_PATH = REPO_ROOT / "apps" / "desktop" / "pyinstaller" / "desktop_package.py"
DESKTOP_CHILD = REPO_ROOT / "server" / "desktop_child.py"

#: AC1's pinned exception-set size, mirrored here so widening the set needs an
#: edit in BOTH files (EXPECTED_TOOL_SCHEMA_SHA256 re-pin discipline). The set
#: was MEASURED EMPTY: two independent 2026-08-09 builds diffed to zero paths
#: once the spec sorted the two observed ordering drifts (base_library.zip
#: members, PYZ TOC); rationale lives beside the driver's frozenset.
PINNED_EXCEPTION_COUNT = 0
PINNED_EXCEPTIONS: frozenset[str] = frozenset()

#: AC2 LaTeX fixtures reused from tests/test_equation_latex_route.py — real
#: query-path inputs, converted independently in the source venv AND inside
#: the frozen bundle within the same test invocation (never a checked-in
#: golden generated by the bundle itself).
LATEX_FIXTURES = [
    r"\int_a^b g(t) dt",
    r"\sum_{n=0}^\infty a_n",
    r"\int_0^1 f(x)dx",
    r"\frac{a}{b}",
    r"\mathbb{C}",
    "x+y",
]

_driver_cache = None


def _driver():
    global _driver_cache
    if _driver_cache is None:
        spec = importlib.util.spec_from_file_location(
            "arxmcp_desktop_package", DRIVER_PATH
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _driver_cache = module
    return _driver_cache


def _frozen_env(tmp_path: Path) -> dict[str, str]:
    """Explicit minimal env for frozen-executable launches: never inherit the
    test runner's environment (conftest sets KMP_DUPLICATE_LIB_OK session-wide,
    which the desktop launch contract forbids)."""
    home = tmp_path / "home"
    tmpdir = tmp_path / "tmp"
    home.mkdir(parents=True, exist_ok=True)
    tmpdir.mkdir(parents=True, exist_ok=True)
    return {
        "PATH": "/usr/bin:/bin",
        "HOME": str(home),
        "TMPDIR": str(tmpdir),
        "LANG": "en_US.UTF-8",
    }



def test_freeze_support_is_first_statement_of_main_guard():
    """AC3 static half: the guard's FIRST statement is freeze_support(), so a
    frozen spawn child is intercepted before main() touches the control stream."""
    tree = ast.parse(DESKTOP_CHILD.read_text(encoding="utf-8"))
    guards = [
        node
        for node in tree.body
        if isinstance(node, ast.If)
        and isinstance(node.test, ast.Compare)
        and isinstance(node.test.left, ast.Name)
        and node.test.left.id == "__name__"
    ]
    assert len(guards) == 1, "expected exactly one __main__ guard"
    first = guards[0].body[0]
    assert isinstance(first, ast.Expr) and isinstance(first.value, ast.Call)
    call = first.value.func
    assert isinstance(call, ast.Attribute) and call.attr == "freeze_support"
    assert isinstance(call.value, ast.Name) and call.value.id == "multiprocessing"



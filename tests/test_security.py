# AC: Mcp-Session-Id is unique + cryptographically secure
# ===========================================================================


class TestSessionId:
    """The MCP 2025-06-18 spec requires session IDs to be ``globally
    unique and cryptographically secure (e.g. a UUID, a JWT, or a
    cryptographic hash)``. The mcp library generates ``uuid4().hex``
    (32 lowercase hex chars, 122 bits of CSRNG entropy via
    ``os.urandom``), which is on the spec's permitted list.

    The brief's preference for ``secrets.token_hex(32)`` (64 hex chars,
    256 bits) is stronger but the mcp library does not expose an
    override knob; overriding would require monkeypatching a private
    attribute. We accept the library default for v1; this test
    enforces a LOOSE shape contract that BOTH 32-hex and 64-hex
    satisfy."""

    def test_session_id_present_and_well_formed(self, warm_app):
        """Initialize an MCP session and verify the response carries
        an ``Mcp-Session-Id`` header that is at least 32 lowercase
        hex chars."""
        r = warm_app.post(
            "/mcp/",
            json={
                "jsonrpc": "2.0",
                "id": 1,
                "method": "initialize",
                "params": {
                    "protocolVersion": "2025-06-18",
                    "capabilities": {},
                    "clientInfo": {"name": "test", "version": "1.0"},
                },
            },
            headers={
                "Accept": "application/json, text/event-stream",
                "Content-Type": "application/json",
                "Host": "127.0.0.1:7733",
            },
        )
        # The library may return the session id in a header or echo it
        # later; in mcp 1.27.1 the initialize response carries it as
        # ``mcp-session-id``.
        sid = r.headers.get("mcp-session-id")
        assert sid is not None, (
            f"expected mcp-session-id header in initialize response; "
            f"got headers={dict(r.headers)}"
        )
        # Loose contract: at least 32 hex chars, all-lowercase. UUID4 hex
        # = 32; secrets.token_hex(32) = 64. Both pass.
        assert len(sid) >= 32, f"session id too short: {sid!r}"
        assert all(c in "0123456789abcdef" for c in sid), (
            f"session id is not all-lowercase-hex: {sid!r}"
        )

    def test_two_sessions_get_different_ids(self, warm_app):
        """Two initialize calls yield distinct session ids — basic
        uniqueness check."""
        sids = []
        for _ in range(2):
            r = warm_app.post(
                "/mcp/",
                json={
                    "jsonrpc": "2.0",
                    "id": 1,
                    "method": "initialize",
                    "params": {
                        "protocolVersion": "2025-06-18",
                        "capabilities": {},
                        "clientInfo": {"name": "test", "version": "1.0"},
                    },
                },
                headers={
                    "Accept": "application/json, text/event-stream",
                    "Content-Type": "application/json",
                    "Host": "127.0.0.1:7733",
                },
            )
            sid = r.headers.get("mcp-session-id")
            if sid is not None:
                sids.append(sid)
        assert len(sids) >= 2
        assert sids[0] != sids[1], (
            "two distinct sessions returned the same id — RNG broken?"
        )



"""Security-hardening tests (E06_S05).

Coverage map (acceptance criteria → test class):

  AC                                                Test class
  ──────────────────────────────────────────────────────────────────────
  Origin: evil.com → HTTP 403                       TestOriginValidation
  No Origin header → request proceeds normally      TestOriginValidation
  ARXMCP_BIND_HOST=0.0.0.0 → exit code 1 + log      TestStartupRejectsBadBind
  X-Content-Type-Options: nosniff on all responses  TestSecurityHeaders
  X-Frame-Options: DENY on all responses            TestSecurityHeaders
  1 MB request body cap                             TestRequestBodyLimit
  Mcp-Session-Id is unique + ≥32 hex chars          TestSessionId

The brief's session-id call ("use ``secrets.token_hex(32)`` not
UUID4") was deliberately deviated from in the implementation:
``uuid4().hex`` is generated by the upstream ``mcp`` library and is
explicitly listed by the MCP 2025-06-18 spec as an acceptable
session-id form ("a UUID, a JWT, or a cryptographic hash").
Overriding the library's generator would require monkeypatching a
private attribute. This test enforces a LOOSE shape contract — at
least 32 hex chars, all-lowercase — that both UUID4 (32 hex) and
``secrets.token_hex(32)`` (64 hex) satisfy. If the library ever
exposes a generator knob, the implementation can switch without
changing this test.

The startup test uses ``subprocess.run`` against ``python -m
server.main`` because the AC is about exit code, not config-parse
exception type (TestConfigValidation in test_server_startup.py
already covers the latter).
"""


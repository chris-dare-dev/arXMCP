class TestOriginValidation:
    """Brief AC #1+#2: Origin: evil → 403; no Origin → pass."""

    def test_evil_origin_rejected_403(self, warm_app):
        """The brief's literal AC: ``curl -H "Origin: https://evil.com"``
        returns HTTP 403."""
        r = warm_app.get("/healthz", headers={"Origin": "https://evil.com"})
        assert r.status_code == 403
        body = r.json()
        assert body["error"] == "origin_forbidden"
        assert body["origin"] == "https://evil.com"

    def test_no_origin_header_proceeds(self, warm_app):
        """The brief's literal AC: no Origin header → request proceeds
        normally (CLI tools and stdio shim do not set Origin)."""
        r = warm_app.get("/healthz")
        assert r.status_code == 200
        assert r.json() == {"status": "ok"}

    def test_localhost_origin_with_port_passes(self, warm_app):
        """``http://localhost:7733`` is the canonical browser-side
        origin for a local dev tool. Must pass."""
        r = warm_app.get(
            "/healthz", headers={"Origin": "http://localhost:7733"}
        )
        assert r.status_code == 200

    def test_127_origin_with_port_passes(self, warm_app):
        r = warm_app.get(
            "/healthz", headers={"Origin": "http://127.0.0.1:7733"}
        )
        assert r.status_code == 200

    def test_ipv6_loopback_origin_passes(self, warm_app):
        r = warm_app.get(
            "/healthz", headers={"Origin": "http://[::1]:7733"}
        )
        assert r.status_code == 200

    def test_localhost_origin_no_port_passes(self, warm_app):
        """Some clients omit the explicit port. ``http://localhost``
        without ``:7733`` is still a loopback origin."""
        r = warm_app.get("/healthz", headers={"Origin": "http://localhost"})
        assert r.status_code == 200

    def test_https_loopback_rejected(self, warm_app):
        """v1 server is http only — ``https://localhost`` is NOT in
        the allow-list. If a future deployment adds TLS, this test
        flips to assert 200."""
        r = warm_app.get(
            "/healthz", headers={"Origin": "https://localhost:7733"}
        )
        assert r.status_code == 403

    def test_origin_evil_subdomain_of_localhost_rejected(self, warm_app):
        """``http://localhost.evil.com`` would be a DNS-rebinding-style
        attack — host component is NOT ``localhost``. Reject."""
        r = warm_app.get(
            "/healthz",
            headers={"Origin": "http://localhost.evil.com"},
        )
        assert r.status_code == 403

    def test_evil_origin_on_metrics_rejected(self, warm_app):
        """Defense-in-depth — FastMCP only protects ``/mcp``. Our
        middleware extends Origin validation to ``/metrics``."""
        r = warm_app.get(
            "/metrics", headers={"Origin": "https://evil.com"}
        )
        assert r.status_code == 403

    def test_evil_origin_response_carries_security_headers(self, warm_app):
        """The 403 must still carry X-Content-Type-Options /
        X-Frame-Options because SecurityHeadersMiddleware is OUTERMOST.
        Closes the dual-AC overlap between Origin validation and
        security headers."""
        r = warm_app.get("/healthz", headers={"Origin": "https://evil.com"})
        assert r.status_code == 403
        assert r.headers.get("x-content-type-options") == "nosniff"
        assert r.headers.get("x-frame-options") == "DENY"


class TestOriginAllowedHelper:
    """Unit tests for the ``_origin_is_allowed`` helper. Belt-and-
    suspenders for the per-test integration coverage above."""

    def test_loopback_hosts_known(self):
        """The constant is the source of truth — assert it matches
        what the docstring promises."""
        assert "127.0.0.1" in LOOPBACK_ORIGIN_HOSTS
        assert "localhost" in LOOPBACK_ORIGIN_HOSTS
        assert "::1" in LOOPBACK_ORIGIN_HOSTS

    @pytest.mark.parametrize("origin", [
        "http://127.0.0.1",
        "http://127.0.0.1:7733",
        "http://localhost",
        "http://localhost:8080",
        "http://[::1]",
        "http://[::1]:7733",
    ])
    def test_allows_loopback(self, origin):
        assert _origin_is_allowed(origin) is True

    @pytest.mark.parametrize("origin", [
        "https://localhost",  # wrong scheme
        "ftp://127.0.0.1",  # wrong scheme
        "http://evil.com",  # wrong host
        "http://127.0.0.2",  # wrong host (close miss)
        "http://localhost.evil.com",  # subdomain attack
        "http://0.0.0.0",  # IPv4 wildcard is NOT loopback
        "http://10.0.0.1",  # private IP, not loopback
        "",  # empty
        "not-a-url",  # malformed
    ])
    def test_rejects_non_loopback(self, origin):
        assert _origin_is_allowed(origin) is False



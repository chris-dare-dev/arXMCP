class TestSecurityHeaders:
    """Brief: ``X-Content-Type-Options: nosniff`` and
    ``X-Frame-Options: DENY`` on all responses."""

    def test_healthz_has_security_headers(self, warm_app):
        r = warm_app.get("/healthz")
        assert r.headers.get("x-content-type-options") == "nosniff"
        assert r.headers.get("x-frame-options") == "DENY"

    def test_readyz_has_security_headers(self, warm_app):
        r = warm_app.get("/readyz")
        assert r.headers.get("x-content-type-options") == "nosniff"
        assert r.headers.get("x-frame-options") == "DENY"

    def test_metrics_has_security_headers(self, warm_app):
        r = warm_app.get("/metrics")
        assert r.headers.get("x-content-type-options") == "nosniff"
        assert r.headers.get("x-frame-options") == "DENY"

    def test_does_not_overwrite_existing_headers(
        self, _seeded_lancedb, _mocked_bge
    ):
        """Idempotency: a downstream handler that already sets the
        header keeps its value. Belt-and-suspenders against accidental
        overwrites of test-route values."""
        cfg = Config(lancedb_path=_seeded_lancedb)
        app = create_app(cfg)

        @app.get("/__test_custom_header")
        async def custom():
            from fastapi.responses import JSONResponse

            return JSONResponse(
                content={"ok": 1},
                headers={"X-Frame-Options": "SAMEORIGIN"},
            )

        with TestClient(app) as client:
            r = client.get("/__test_custom_header")
            assert r.status_code == 200
            # Custom value wins; we still added nosniff (no conflict).
            assert r.headers.get("x-frame-options") == "SAMEORIGIN"
            assert r.headers.get("x-content-type-options") == "nosniff"



// Stamps src/api/schema.d.ts with the sha256 of the openapi.json it was
// generated from. tests/test_design_gates.py (repo pytest suite) compares
// this stamp against the live repo-root dump so IF-1 drift is a visible
// test failure, not a silent stale client.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dumpPath = join(here, "..", "..", "openapi.json");
const schemaPath = join(here, "..", "src", "api", "schema.d.ts");

const hash = createHash("sha256").update(readFileSync(dumpPath)).digest("hex");
const body = readFileSync(schemaPath, "utf8");
const stamped = `/* generated by \`npm run gen:api\` from ../openapi.json (IF-1)\n * source-sha256: ${hash}\n * DO NOT EDIT BY HAND. */\n${body}`;
writeFileSync(schemaPath, stamped);
console.log(`stamped schema.d.ts with source-sha256 ${hash.slice(0, 12)}…`);
